"""Grid-independence study: GCI / Richardson extrapolation over mesh levels, plus a
check of which coarse level still reproduces the *difference* between two designs
(the low-fidelity level a multi-fidelity surrogate can use).

    # 1. geometry for each configuration (half models)
    python scripts/build_car.py --half
    python scripts/build_car.py --half --fw-flap-delta -10 --rw-flap-delta -25 --name low_drag

    # 2. cases + Slurm scripts, send to the cluster, submit
    python scripts/grid_study.py prepare grid1 --configs baseline=cad/out/baseline_half low_drag=cad/out/low_drag_half
    set F1CFD_HPC=user@host:port            (or --host)
    set F1CFD_NODES=node_a node_b           (or prepare --nodes)
    python scripts/grid_study.py push grid1
    python scripts/grid_study.py status grid1
    python scripts/grid_study.py fetch grid1      # logs + forces only
    python scripts/grid_study.py analyze grid1

GCI follows Celik et al. (2008), "Procedure for estimation and reporting of uncertainty
due to discretization in CFD applications", J. Fluids Eng. 130(7), 078001.
"""
import argparse
import json
import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from make_cfd_case import LEVELS  # noqa: E402

RUNS = ROOT / "cfd" / "runs"
DEFAULT_NP = {"L1": 8, "L2": 16, "L3": 32, "L4": 32, "L5": 64}
PARTS = ("total", "front_wing", "body", "rear_wing", "wheels")


# ------------------------------------------------------------------ prepare / submit

SUBMIT = """#!/bin/bash
#SBATCH -J {job}
#SBATCH -N 1
#SBATCH -n {np}
#SBATCH -p {partition}
#SBATCH -o slurm-%j.log
cd "${{SLURM_SUBMIT_DIR:?}}"
source "${{FOAM_ENV:-$HOME/ofenv.sh}}" || true
bash Allrun
"""


def cmd_prepare(a):
    """New study, or with --add extra levels/configs appended to an existing one.
    Each call is a batch with its own submit script; push sends the latest batch."""
    study = RUNS / a.study
    if study.exists() and not a.add:
        sys.exit(f"{study.relative_to(ROOT)} exists (use --add to append levels)")
    if a.add:
        meta = json.loads((study / "study.json").read_text(encoding="utf-8"))
        configs = dict(c.split("=", 1) for c in a.configs) if a.configs else meta["configs"]
    else:
        if not a.configs:
            sys.exit("--configs is required for a new study")
        configs = dict(c.split("=", 1) for c in a.configs)
        if not a.nodes:
            sys.exit("give --nodes or set F1CFD_NODES (space-separated Slurm node names)")
        meta = dict(study=a.study, configs=configs, levels=[], iter=a.iter, u=a.u, cases=[],
                    nodes=a.nodes, core_cap=a.core_cap, partition=a.partition, batches=[])
    nps = dict(DEFAULT_NP, **dict(x.split("=") for x in a.np))
    existing = {c["name"] for c in meta["cases"]}
    cases = []
    for cname, geom in configs.items():
        for lev in a.levels:
            name = f"{cname}_{lev}"
            if name in existing:
                continue
            subprocess.check_call([sys.executable, str(ROOT / "scripts" / "make_cfd_case.py"),
                                   "--geom", geom, "--level", lev, "--np", str(nps[lev]),
                                   "--iter", str(a.iter), "--u", str(a.u), "--name", name,
                                   "--outdir", str(study.relative_to(ROOT))])
            (study / name / "submit.sh").write_bytes(
                SUBMIT.format(job=name, np=nps[lev], partition=a.partition).encode())
            cases.append(dict(name=name, config=cname, level=lev, np=int(nps[lev])))
    if not cases:
        sys.exit("nothing new to prepare")
    meta["configs"].update(configs)
    meta["levels"] = sorted(set(meta["levels"]) | set(a.levels), key=lambda l: int(l[1:]))
    meta["cases"] += cases
    batches = meta.setdefault("batches", [])
    if not batches and existing:      # study made before batches were recorded
        batches.append(dict(script="submit_all.sh", cases=sorted(existing)))
    script = "submit_all.sh" if not batches else f"submit_batch{len(batches) + 1}.sh"
    batches.append(dict(script=script, cases=[c["name"] for c in cases]))
    (study / "study.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    (study / script).write_bytes(submit_script(meta, cases).encode())
    print(f"prepared {len(cases)} cases in {study.relative_to(ROOT)} (batch {len(batches)}, {script})")


def submit_script(meta, cases):
    """One node per configuration. On each node the biggest jobs start at once up to
    core_cap cores; the rest wait (afterany) for the smallest of those to finish."""
    lines = ["#!/bin/bash", "# generated by grid_study.py - run from the study folder",
             'cd "$(dirname "$0")"', "set -e"]
    by_cfg = {}
    for c in cases:
        by_cfg.setdefault(c["config"], []).append(c)
    for i, (cfg, cs) in enumerate(by_cfg.items()):
        node = meta["nodes"][i % len(meta["nodes"])]
        cs = sorted(cs, key=lambda c: -c["np"])
        now, later, used = [], [], 0
        for c in cs:
            if used + c["np"] <= meta["core_cap"]:
                now.append(c)
                used += c["np"]
            else:
                later.append(c)
        lines.append(f"# {cfg} on {node}")
        for c in now:
            lines.append(f'j_{c["name"]}=$(cd {c["name"]} && sbatch --parsable -w {node} submit.sh)')
            lines.append(f'echo "{c["name"]} -> job $j_{c["name"]} ({node})"')
        gate = min(now, key=lambda c: c["np"])["name"] if now and later else None
        for c in later:
            dep = f"--dependency=afterany:$j_{gate} " if gate else ""
            lines.append(f'j_{c["name"]}=$(cd {c["name"]} && sbatch --parsable {dep}-w {node} submit.sh)')
            lines.append(f'echo "{c["name"]} -> job $j_{c["name"]} ({node}, after {gate})"')
    return "\n".join(lines) + "\n"


def hpc(a):
    spec = a.host or os.environ.get("F1CFD_HPC")
    if not spec:
        sys.exit("set F1CFD_HPC=user@host:port or pass --host")
    host, _, port = spec.partition(":")
    return host, port or "22"


def ssh(a, remote_cmd, **kw):
    host, port = hpc(a)
    return subprocess.run(["ssh", "-p", port, "-o", "BatchMode=yes", host, remote_cmd], **kw)


def cmd_push(a):
    """Send the latest batch (its cases + study.json + submit script) and submit it."""
    study = RUNS / a.study
    meta = json.loads((study / "study.json").read_text(encoding="utf-8"))
    batches = meta.get("batches") or [dict(script="submit_all.sh", cases=[c["name"] for c in meta["cases"]])]
    batch = batches[-1]
    remote = f"f1cfd/{a.study}"
    files = [f"{a.study}/study.json", f"{a.study}/{batch['script']}"] + [f"{a.study}/{c}" for c in batch["cases"]]
    # relative paths: GNU tar reads "C:..." as a remote host
    tar = subprocess.Popen(["tar", "czf", "-"] + files, stdout=subprocess.PIPE, cwd=RUNS)
    r = ssh(a, f"mkdir -p f1cfd && tar xzf - -C f1cfd && echo unpacked {len(batch['cases'])} cases into {remote}",
            stdin=tar.stdout)
    tar.wait()
    if r.returncode or tar.returncode:
        sys.exit("transfer failed")
    if not a.no_submit:
        fix = " ".join([batch["script"]] + [f"{c}/submit.sh {c}/Allrun" for c in batch["cases"]])
        ssh(a, f"cd {remote} && sed -i 's/\\r$//' {fix} && bash {batch['script']}")


def cmd_status(a):
    remote = f"f1cfd/{a.study}"
    script = (f"squeue -u $USER -o '%i %j %T %M %R'; cd {remote} 2>/dev/null || exit; "
              "for d in */; do d=${d%/}; it=$(grep -c '^Time = ' $d/log.simpleFoam 2>/dev/null); "
              "st=$(tail -1 $d/log.timing 2>/dev/null | cut -d' ' -f1-2); "
              "echo \"$d  last-step: ${st:-queued}  iterations: ${it:-0}\"; done")
    ssh(a, script)


def cmd_fetch(a):
    study = RUNS / a.study
    remote = f"f1cfd/{a.study}"
    pat = "*/log.* */postProcessing */slurm-*.log"
    host, port = hpc(a)
    p = subprocess.Popen(["ssh", "-p", port, "-o", "BatchMode=yes", host,
                          f"cd {remote} && tar czf - --ignore-failed-read {pat} 2>/dev/null"],
                         stdout=subprocess.PIPE)
    subprocess.check_call(["tar", "xzf", "-"], stdin=p.stdout, cwd=study)
    p.wait()
    print(f"fetched logs and forces into {study.relative_to(ROOT)}")


# ------------------------------------------------------------------ analysis

def case_result(case, q, window):
    res = {}
    m = re.search(r"^\s*cells:\s+(\d+)", (case / "log.checkMesh").read_text(errors="ignore"), re.M) \
        if (case / "log.checkMesh").exists() else None
    res["cells"] = int(m.group(1)) if m else None
    res["iters"] = 0
    for part in PARTS:
        f = case / "postProcessing" / f"forces_{part}" / "0" / "force.dat"
        if not f.exists():
            continue
        a = np.loadtxt(f, comments="#")
        if a.ndim < 2 or len(a) < 10:
            continue
        w = a[-min(window, len(a)):]
        cla, cda = -2 * w[:, 3] / q, 2 * w[:, 1] / q
        res[part] = dict(cla=cla.mean(), cda=cda.mean(), cla_band=np.ptp(cla), cda_band=np.ptp(cda),
                         cla_se=mean_se(cla), cda_se=mean_se(cda))
        res["iters"] = max(res["iters"], len(a))
    snap = case / "log.snappyHexMesh"
    if snap.exists():
        txt = snap.read_text(errors="ignore")
        # layer table: patch faces target mesh(avg layers) thickness[m] thickness[% of target]
        cov = re.findall(r"^(body|front_wing|rear_wing|wheels_front|wheels_rear)\s+\d+\s+\d+\s+"
                         r"([\d.]+)\s+[\d.eE+-]+\s+([\d.]+)", txt, re.M)
        res["layers"] = {p: (float(n), float(pct)) for p, n, pct in cov}
    yp = sorted(case.glob("postProcessing/yPlus/*/yPlus.dat"))
    if yp:
        rows = [l.split() for l in yp[-1].read_text().splitlines() if l and not l.startswith("#")]
        last = rows[-1][0] if rows else None
        res["yplus"] = {r[1]: float(r[4]) for r in rows if r[0] == last}
    return res


def mean_se(y, max_lag=300):
    """Standard error of the mean of a correlated series (integrated autocorrelation time)."""
    x = y - y.mean()
    if not x.any():
        return 0.0
    ac = np.correlate(x, x, "full")[len(x) - 1:]
    ac = ac / ac[0]
    lag = ac[1:max_lag]
    cut = np.argmax(lag <= 0) if (lag <= 0).any() else len(lag)
    tau = 1 + 2 * lag[:cut].sum()
    return float(y.std() / np.sqrt(len(y) / tau))


def gci_valid(g, eps, se):
    """Richardson extrapolation is only meaningful in the asymptotic range: monotonic
    convergence, a plausible observed order, and level-to-level changes that stand
    clear of the iterative/statistical uncertainty of the averaged values."""
    why = []
    if g["oscillatory"]:
        why.append("non-monotonic")
    if not (0.5 <= g["p"] <= 3.0):
        why.append(f"order p={g['p']:.2f} outside 0.5-3")
    if min(abs(e) for e in eps) < 2 * se:
        why.append("changes within 2x statistical error")
    return not why, why


def gci(phi, n_cells):
    """Celik et al. (2008). phi, n_cells ordered fine -> coarse (3 grids)."""
    (f1, f2, f3), (n1, n2, n3) = phi, n_cells
    h1, h2, h3 = (n ** (-1 / 3) for n in (n1, n2, n3))
    r21, r32 = h2 / h1, h3 / h2
    e21, e32 = f2 - f1, f3 - f2
    out = dict(r21=r21, r32=r32, oscillatory=False)
    if abs(e21) < 1e-12:
        return dict(out, p=float("nan"), ext=f1, ea21=0.0, gci21=0.0)
    s = np.sign(e32 / e21)
    out["oscillatory"] = bool(s < 0)
    p = 2.0
    for _ in range(200):
        q = np.log((r21 ** p - s) / (r32 ** p - s))
        p_new = abs(np.log(abs(e32 / e21)) + q) / np.log(r21)
        if abs(p_new - p) < 1e-8:
            break
        p = p_new
    ext = (r21 ** p * f1 - f2) / (r21 ** p - 1)
    ea21 = abs((f1 - f2) / f1)
    return dict(out, p=float(p), ext=float(ext), ea21=float(ea21),
                eext21=float(abs((ext - f1) / ext)), gci21=float(1.25 * ea21 / (r21 ** p - 1)))


def cmd_analyze(a):
    study = RUNS / a.study
    meta = json.loads((study / "study.json").read_text(encoding="utf-8"))
    q = 0.5 * 1.2 * meta["u"] ** 2
    levels = meta["levels"]
    R = {}
    for c in meta["cases"]:
        d = study / c["name"]
        if (d / "postProcessing").exists():
            R.setdefault(c["config"], {})[c["level"]] = case_result(d, q, a.window)

    lines = [f"# Grid study `{a.study}`", "",
             f"U = {meta['u']} m/s, half model doubled to the full car, CL*A positive = downforce, "
             f"mean (and peak-to-peak band) over the last {a.window} iterations.", ""]
    report = {}
    for cfg, by_lev in R.items():
        lines += [f"## {cfg}", "", "| level | h0 [m] | cells | iters | CL*A [m^2] | CD*A [m^2] | "
                  "FW CL*A | body CL*A | RW CL*A |", "|---|---|---|---|---|---|---|---|---|"]
        done = [l for l in levels if l in by_lev and "total" in by_lev[l] and by_lev[l]["cells"]]
        for l in done:
            r = by_lev[l]
            t = r["total"]
            parts = " | ".join(f"{r[p]['cla']:.3f}" if p in r else "-" for p in ("front_wing", "body", "rear_wing"))
            lines.append(f"| {l} | {LEVELS[l]['h0']} | {r['cells']:,} | {r['iters']} | "
                         f"{t['cla']:.3f} ({t['cla_band']:.3f}) | {t['cda']:.3f} ({t['cda_band']:.3f}) | {parts} |")
        lines.append("")
        report[cfg] = {}
        for qty in ("cla", "cda"):
            trip = done[-3:]
            if len(trip) < 3:
                continue
            fine_first = trip[::-1]
            vals = [R[cfg][l]["total"][qty] for l in fine_first]
            g = gci(vals, [R[cfg][l]["cells"] for l in fine_first])
            se = max(R[cfg][l]["total"][qty + "_se"] for l in fine_first)
            valid, why = gci_valid(g, (vals[1] - vals[0], vals[2] - vals[1]), se)
            label = {"cla": "CL*A", "cda": "CD*A"}[qty]
            spread = (max(vals) - min(vals)) / np.mean(vals)
            if valid:
                ok = [l for l in done if abs(R[cfg][l]["total"][qty] - g["ext"]) / abs(g["ext"]) <= a.hf_tol]
                lines.append(f"- {label}: grids {', '.join(fine_first)} -> p = {g['p']:.2f}, extrapolated = "
                             f"{g['ext']:.3f}, GCI_fine = {100 * g['gci21']:.2f} %"
                             + (" (GCI > 20 %: far from converged, extrapolated value not reliable)"
                                if g["gci21"] > 0.2 else "")
                             + f"; first level within {100 * a.hf_tol:.0f} % of extrapolation: "
                             + (ok[0] if ok else "none"))
            else:
                ok = []
                lines.append(f"- {label}: grids {', '.join(fine_first)} not in the asymptotic range "
                             f"({'; '.join(why)}) -> no Richardson extrapolation / GCI. Spread over these "
                             f"grids {100 * spread:.1f} %, statistical error of each mean <= {se:.3f} m^2")
            report[cfg][qty] = dict(g, levels=fine_first, valid=valid, why=why, se=se, spread=spread,
                                    hf_level=ok[0] if ok else None)
        for l in done:
            if "layers" in R[cfg][l] and R[cfg][l]["layers"]:
                cov = ", ".join(f"{p} {v[0]:.2f} layers/{v[1]:.0f}%" for p, v in R[cfg][l]["layers"].items())
                yp = R[cfg][l].get("yplus", {})
                ypt = ", ".join(f"{p} {v:.0f}" for p, v in yp.items() if p in ("body", "front_wing", "rear_wing"))
                lines.append(f"- {l} prism layers (mean count / thickness vs target): {cov}" + (f"; mean y+: {ypt}" if ypt else ""))
        lines.append("")

    cfgs = list(R)
    if len(cfgs) >= 2:
        b, v = cfgs[0], cfgs[1]
        common = [l for l in levels if l in R[b] and l in R[v] and "total" in R[b][l] and "total" in R[v][l]]
        if common:
            ref = common[-1]
            lines += [f"## Trend check: {v} - {b}", "",
                      f"Difference between the two designs at each level, relative to the finest level ({ref}).", "",
                      "| level | dCL*A | dCD*A | dCL*A vs finest | dCD*A vs finest |", "|---|---|---|---|---|"]
            dref = {k: R[v][ref]["total"][k] - R[b][ref]["total"][k] for k in ("cla", "cda")}
            lf = None
            for l in common:
                d = {k: R[v][l]["total"][k] - R[b][l]["total"][k] for k in ("cla", "cda")}
                rel = {k: (d[k] - dref[k]) / abs(dref[k]) if abs(dref[k]) > 1e-9 else float("nan") for k in d}
                lines.append(f"| {l} | {d['cla']:+.3f} | {d['cda']:+.3f} | {100 * rel['cla']:+.1f} % | {100 * rel['cda']:+.1f} % |")
                same_sign = all(np.sign(d[k]) == np.sign(dref[k]) for k in d)
                if lf is None and l != ref and same_sign and all(abs(rel[k]) <= a.lf_tol for k in rel):
                    lf = l
            lines += ["", f"Coarsest level whose design difference is within {100 * a.lf_tol:.0f} % of the finest level "
                          f"(same sign): **{lf or 'none'}**", ""]
            report["trend"] = dict(reference=ref, lf_level=lf)

    out = study / "grid_study.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    (study / "grid_study.json").write_text(json.dumps(report, indent=2, default=float), encoding="utf-8")
    print("\n".join(lines))
    plot(R, levels, report, study / "grid_study.png")
    print(f"\nwrote {out.relative_to(ROOT)} and grid_study.png")


def plot(R, levels, report, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.family": "serif", "font.size": 10, "xtick.direction": "in",
                         "ytick.direction": "in", "xtick.top": True, "ytick.right": True})
    colors = ["#1f3b73", "#b0413e", "#3f7f4f"]
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.6))
    for ax, qty, lab in zip(axes, ("cla", "cda"), (r"$C_L A$ [m$^2$]", r"$C_D A$ [m$^2$]")):
        for i, (cfg, by_lev) in enumerate(R.items()):
            ls = [l for l in levels if l in by_lev and "total" in by_lev[l] and by_lev[l]["cells"]]
            h = [by_lev[l]["cells"] ** (-1 / 3) * 100 for l in ls]
            y = [by_lev[l]["total"][qty] for l in ls]
            err = [2 * by_lev[l]["total"][qty + "_se"] for l in ls]
            ax.errorbar(h, y, yerr=err, fmt="o-", color=colors[i % 3], label=cfg, ms=4, lw=1, capsize=2)
            for hh, yy, l in zip(h, y, ls):
                ax.annotate(l, (hh, yy), textcoords="offset points", xytext=(4, 4), fontsize=8)
            g = report.get(cfg, {}).get(qty)
            if g and g.get("valid") and g["gci21"] <= 0.2:
                ax.plot([0], [g["ext"]], "s", mfc="none", color=colors[i % 3], ms=6)
                ax.plot([0, h[-1]], [g["ext"], y[-1]], ":", color=colors[i % 3], lw=0.8)
        ax.set_xlabel(r"$N^{-1/3}\times 100$  (representative cell size)")
        ax.set_ylabel(lab)
        ax.set_xlim(left=-0.02)
    axes[0].legend(frameon=False)
    fig.text(0.5, 0.005, "error bars: 2 x standard error of the iteration-averaged value; open squares: "
             "Richardson extrapolation (only where the grids are in the asymptotic range)", ha="center", fontsize=8)
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    fig.savefig(path, dpi=150)
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", help="user@host:port of the cluster (default: $F1CFD_HPC)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("prepare")
    p.add_argument("study")
    p.add_argument("--configs", nargs="+", help="name=geometry_folder (half model)")
    p.add_argument("--add", action="store_true", help="append levels to an existing study")
    p.add_argument("--levels", nargs="+", default=["L1", "L2", "L3", "L4"])
    p.add_argument("--np", nargs="*", default=[], help="override ranks, e.g. L4=48")
    p.add_argument("--iter", type=int, default=3000)
    p.add_argument("--u", type=float, default=50.0)
    p.add_argument("--nodes", nargs="+", default=os.environ.get("F1CFD_NODES", "").split() or None,
                   help="Slurm node names, one configuration per node (default: $F1CFD_NODES)")
    p.add_argument("--core-cap", type=int, default=64, help="max cores per node at once")
    p.add_argument("--partition", default="long")
    for name in ("push", "status", "fetch"):
        s = sub.add_parser(name)
        s.add_argument("study")
        if name == "push":
            s.add_argument("--no-submit", action="store_true")
    s = sub.add_parser("analyze")
    s.add_argument("study")
    s.add_argument("--window", type=int, default=1000, help="iterations averaged at the end")
    s.add_argument("--hf-tol", type=float, default=0.02, help="HF level: within this of extrapolation")
    s.add_argument("--lf-tol", type=float, default=0.10, help="LF level: design delta within this of finest")
    a = ap.parse_args()
    {"prepare": cmd_prepare, "push": cmd_push, "status": cmd_status,
     "fetch": cmd_fetch, "analyze": cmd_analyze}[a.cmd](a)


if __name__ == "__main__":
    main()
